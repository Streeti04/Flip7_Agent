#!/usr/bin/env python3
"""Build self-contained tournament submissions from the package sources.

The grader's submission loader copies only ``submissions/<name>/`` — the custom
modules developed here (``flip7.belief``, ``flip7.agents.heuristic_agent``,
``flip7.observation``) are not guaranteed to ship. Each submission therefore
embeds the exact package code (imports stripped, concatenated in dependency
order). ``submissions/README.md`` specifies a *single* ``agent.py`` per folder,
so the RL actor weights are embedded too (base64 of the compressed npz); the
npz copy written beside it is only a secondary source. A behaviour-equivalence
test (tests/test_submissions_sync.py) keeps the copies honest.
"""

from __future__ import annotations

import argparse
import base64
import re
import shutil
from pathlib import Path
import sys

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

ROOT = Path(__file__).resolve().parents[1]
SUBMISSIONS = ROOT / "submissions"

from flip7.agents.rl_agent import ENDGAME_BUST_VALUE

_HEADER = '''"""Self-contained tournament submission (auto-generated by scripts/build_submissions.py).

Only the *provided* Flip 7 package (card / game_state / action / player /
agents.base_agent), the standard library, and NumPy are imported — the
submission folder is fully independent of any custom development modules.

NOTE: deliberately no ``from __future__ import annotations`` — on Python 3.14
dataclasses crash during module exec when the loader does not register the
module in ``sys.modules`` before exec (which submission_loader.py does not).
"""

from dataclasses import dataclass, replace
from pathlib import Path

import numpy as np

from flip7.action import Action
from flip7.agents.base_agent import Action as _Action
from flip7.agents.base_agent import BaseAgent
from flip7.card import ActionCard, BonusCard, DECK_COMPOSITION, NumberCard
from flip7.game_state import GameState, PlayerView
from flip7.player import PlayerStatus

'''

_STRIP_PATTERNS = (
    re.compile(r'^from __future__ import.*\n', re.MULTILINE),
    re.compile(r'^from \..*\n', re.MULTILINE),
    re.compile(r'^from flip7\..*\n', re.MULTILINE),
    re.compile(r'^import .*\n', re.MULTILINE),
)


def _body(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    # Drop the module docstring (first triple-quoted block).
    text = re.sub(r'\A"""(?:[^"]|"(?!""))*"""\n', "", text)
    for pattern in _STRIP_PATTERNS:
        text = pattern.sub("", text)
    return text.strip("\n")


def build_heuristic_submission() -> Path:
    target_dir = SUBMISSIONS / "flip7_heuristic"
    target_dir.mkdir(parents=True, exist_ok=True)
    core = "\n\n".join(
        [
            "# " + "-" * 74,
            "# Belief-state model (mirror of flip7/belief.py)",
            "# " + "-" * 74,
            _body(ROOT / "flip7" / "belief.py"),
            "# " + "-" * 74,
            "# Expectimax heuristic (mirror of flip7/agents/heuristic_agent.py)",
            "# " + "-" * 74,
            _body(ROOT / "flip7" / "agents" / "heuristic_agent.py"),
            "",
            "Agent = HeuristicAgent",
            "",
        ]
    )
    target = target_dir / "agent.py"
    target.write_text(_HEADER + core, encoding="utf-8")
    return target


def _actor_literal(actor: Path | None) -> str:
    """The actor npz as a parenthesised base64 string literal (76-char lines)."""
    if actor is None or not actor.is_file():
        return '    ""'
    encoded = base64.b64encode(actor.read_bytes()).decode("ascii")
    return "\n".join(f'    "{encoded[i:i + 76]}"' for i in range(0, len(encoded), 76))


def build_rl_submission(actor: Path | None) -> Path:
    target_dir = SUBMISSIONS / "flip7_rl"
    target_dir.mkdir(parents=True, exist_ok=True)
    loader = '''

# ----------------------------------------------------------------------
# Tournament agent: NumPy actor if compatible weights exist, heuristic fallback.
# ----------------------------------------------------------------------

import base64 as _base64
import io as _io

# Actor weights (np.savez_compressed, base64). Empty if built without actor.
_ACTOR_NPZ_B64 = (
__ACTOR_B64__
)

class Agent(BaseAgent):
    """MaskablePPO actor inference with a self-contained heuristic fallback."""

    def __init__(self) -> None:
        self._fallback = HeuristicAgent()
        # Mirror of flip7.agents.rl_agent.RLAgent: endgame Stop/Draw override.
        self._endgame = HeuristicAgent(
            HeuristicConfig(endgame_bust_value=__ENDGAME_BUST_VALUE__)
        )
        self._layers: list[tuple[np.ndarray, np.ndarray]] = []
        self._n_players = 4
        # Embedded weights first (agent.py must work on its own), then an
        # optional rl_actor.npz beside this file; otherwise heuristic fallback.
        if not self._load(lambda: _io.BytesIO(_base64.b64decode(_ACTOR_NPZ_B64))):
            self._load(lambda: Path(__file__).with_name("rl_actor.npz"))

    def _load(self, source) -> bool:
        try:
            with np.load(source(), allow_pickle=False) as data:
                n_players = int(data["n_players"].item())
                count = int(data["layer_count"].item())
                layers = [
                    (
                        np.asarray(data[f"weight_{i}"], dtype=np.float32),
                        np.asarray(data[f"bias_{i}"], dtype=np.float32),
                    )
                    for i in range(count)
                ]
            if not layers:
                return False
            self._n_players, self._layers = n_players, layers
            return True
        except Exception:
            # Missing, corrupt or unreadable weights must never crash a tournament.
            return False

    def act(self, gs, legal_actions):
        if not legal_actions:
            return self._fallback.act(gs, legal_actions)
        try:
            if (
                Action.STOP in legal_actions
                and Action.DRAW in legal_actions
                and gs.my_total_score + gs.my_round_score >= 200
            ):
                # Banking now would end the game, a bust only costs this round:
                # delegate to the endgame-aware heuristic (see RLAgent.act).
                return self._endgame.act(gs, legal_actions)
        except Exception:
            pass
        if self._compatible(gs):
            try:
                x = encode_game_state(gs, self._n_players)
                for index, (weight, bias) in enumerate(self._layers):
                    x = weight @ x + bias
                    if index < len(self._layers) - 1:
                        x = np.tanh(x)
                masked = np.full(len(Action), -np.inf, dtype=np.float32)
                for action in legal_actions:
                    masked[int(action)] = x[int(action)]
                selected = _Action(int(np.argmax(masked)))
                if selected in legal_actions:
                    return selected
            except Exception:
                pass  # any inference problem degrades to the heuristic
        return self._fallback.act(gs, legal_actions)

    def _compatible(self, gs) -> bool:
        if not self._layers or len(gs.opponents) + 1 != self._n_players:
            return False
        return self._layers[0][0].shape[-1] == observation_size(self._n_players)
'''
    core = "\n\n".join(
        [
            "# " + "-" * 74,
            "# Belief-state model (mirror of flip7/belief.py)",
            "# " + "-" * 74,
            _body(ROOT / "flip7" / "belief.py"),
            "# " + "-" * 74,
            "# Expectimax heuristic (mirror of flip7/agents/heuristic_agent.py; used as fallback)",
            "# " + "-" * 74,
            _body(ROOT / "flip7" / "agents" / "heuristic_agent.py"),
            "# " + "-" * 74,
            "# Observation encoder (mirror of flip7/observation.py)",
            "# " + "-" * 74,
            _body(ROOT / "flip7" / "observation.py"),
            loader.replace("__ENDGAME_BUST_VALUE__", repr(ENDGAME_BUST_VALUE)).replace(
                "__ACTOR_B64__", _actor_literal(actor)
            ),
        ]
    )
    target = target_dir / "agent.py"
    target.write_text(_HEADER + core, encoding="utf-8")

    if actor is not None and actor.is_file():
        shutil.copy2(actor, target_dir / "rl_actor.npz")
    return target


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--actor",
        type=Path,
        default=None,
        help="npz actor to embed into the RL submission (default: Ergebnisse/rl_actor.npz)",
    )
    args = parser.parse_args()

    actor = args.actor
    if actor is None:
        # Same actor the package RLAgent loads by default.
        for candidate in (ROOT / "Ergebnisse" / "rl_actor.npz",):
            if candidate.is_file():
                actor = candidate
                break

    heuristic_path = build_heuristic_submission()
    rl_path = build_rl_submission(actor)
    print(f"wrote {heuristic_path}")
    print(f"wrote {rl_path} (actor: {actor if actor and actor.is_file() else 'NONE — fallback mode'})")


if __name__ == "__main__":
    main()
